"""
Downloads the site's fonts from Google Fonts once, so visitors never contact Google
(no IP address goes to a third party). Writes:

    assets/fonts/*.woff2      latin + latin-ext only (covers č ć š ž đ)
    assets/fonts/fonts.css    @font-face rules pointing at the local files
    assets/fonts/OFL-*.txt    the SIL Open Font License that ships with each family

    python tools/fetch_fonts.py
"""
from pathlib import Path
import re
import subprocess
import time

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "fonts"
CSS_URL = ("https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,300..900"
           "&family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500&display=swap")
LICENSES = {
    "OFL-Archivo.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/archivo/OFL.txt",
    "OFL-Geist.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/geist/OFL.txt",
    "OFL-GeistMono.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/geistmono/OFL.txt",
}
KEEP = {"latin", "latin-ext"}
# a current browser user agent, otherwise Google answers with old formats
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36"


def get(url):
    # curl rather than urllib: on this machine Python's own connections get refused
    for attempt in range(5):
        r = subprocess.run(["curl", "-s", "-f", "-A", UA, url], capture_output=True)
        if r.returncode == 0 and r.stdout:
            return r.stdout
        time.sleep(2)
    raise RuntimeError(f"download failed: {url}")


OUT.mkdir(parents=True, exist_ok=True)
css = get(CSS_URL).decode("utf-8")

# Google's CSS is a list of "/* subset */ @font-face {...}" blocks
blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
rules, seen = [], {}
for subset, block in blocks:
    if subset not in KEEP:
        continue
    family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
    if url not in seen:  # a variable font serves every weight from one file
        name = f"{family.lower().replace(' ', '-')}-{subset}-{len(seen) + 1}.woff2"
        data = get(url)
        (OUT / name).write_bytes(data)
        seen[url] = name
        print(f"{name:40s} {len(data) // 1024} KB")
    rules.append(f"/* {subset} */\n" + block.replace(url, seen[url]))

header = ("/* Self-hosted fonts (SIL Open Font License, see OFL-*.txt).\n"
          "   Generated by tools/fetch_fonts.py; latin + latin-ext subsets only. */\n\n")
(OUT / "fonts.css").write_text(header + "\n\n".join(rules) + "\n", encoding="utf-8")
print(f"fonts.css: {len(rules)} @font-face rules")

for name, url in LICENSES.items():
    (OUT / name).write_bytes(get(url))
    print(name)
